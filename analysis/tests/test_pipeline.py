"""End-to-end checks on the autopilot reference logs and on simulated participants.

    cd analysis && python -m pytest -q
"""
from pathlib import Path
import numpy as np
import pytest
from sandwich import load, segment, evaluate, domain_from_session, simulate, models, fixations, gaze_data
from sandwich.segment import Action

EX = sorted((Path(__file__).resolve().parents[2] / "examples").glob("autopilot_*.json"))


@pytest.fixture(scope="module", params=EX, ids=[p.stem for p in EX])
def sess(request):
    return load(request.param)


def test_segmentation_finds_the_task(sess):
    names = [a.name for a in segment(sess)]
    for need in ("open_bag", "slice_to_plate", "open_jar:pb", "open_jar:jelly", "take_knife", "dip:pb", "dip:jelly", "close"):
        assert need in names, f"{need} missing from {names}"
    assert any(n.startswith("spread:pb") for n in names) and any(n.startswith("spread:jelly") for n in names)


def test_optimal_plan_replays_with_zero_regret(sess):
    D, s0 = domain_from_session(sess)
    cost, plan = D.solve(s0)
    assert np.isfinite(cost) and plan[-1][0] == "bell"
    acts = [Action(a, h, i, i, i) for i, (a, h, _, _) in enumerate(plan)]
    R = evaluate(sess, acts)
    assert R.efficiency == pytest.approx(1.0, abs=1e-6)
    assert max(abs(float(s["regret"])) for s in R.steps) < 1e-6


def test_perturbed_plans_are_less_efficient(sess):
    D, s0 = domain_from_session(sess)
    _, plan = D.solve(s0)
    rng = np.random.default_rng(0)
    effs = []
    for _ in range(5):
        seq = simulate.perturb_plan([(a, h) for a, h, _, _ in plan], rng, p_swap=0.3, p_extra=0.2)
        effs.append(evaluate(sess, [Action(a, h, i, i, i) for i, (a, h) in enumerate(seq)]).efficiency)
    assert max(effs) <= 1.0 + 1e-9 and np.mean(effs) < 0.97


def test_observed_autopilot_is_near_but_not_above_optimal(sess):
    R = evaluate(sess, segment(sess))
    assert 0.5 < R.efficiency <= 1.0 + 1e-9


def test_online_and_offline_fixations_agree(sess):
    off = fixations(sess); on = sess.ev("fixation")
    assert abs(len(off) - len(on)) <= max(3, 0.15 * len(on))


def test_attention_model_recovery():
    gens = {g: [simulate.simulate_gaze(simulate.TRUE[g], seed=10 * i + k, n_reps=1) for i in range(2)] for k, g in enumerate(["saliency", "plan"])}
    for g, gds in gens.items():
        trials = {f"{g}{i}": models.design(gd) for i, gd in enumerate(gds)}
        best = models.compare(trials, models=["null", "saliency", "jit", "plan"]).model.iloc[0]
        assert best == g, f"data generated by {g} were best fit by {best}"
